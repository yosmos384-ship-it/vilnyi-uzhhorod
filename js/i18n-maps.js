export const MAPS_LANGS = Object.keys(M);
export function mt(key, vars) {
  let s = M[lang]?.[key] ?? M.uk[key] ?? M.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}
